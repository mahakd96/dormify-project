"""
GET /api/transfers/ (TransferViewSet / TransferSerializer) performance
regression + correctness tests.

History:
- Group 1 audit (project-quality/performance/PERFORMANCE_FINAL_REPORT.md,
  finding G1-13): measured `total_queries` scaling linearly with transfer
  count - 101 queries at N=25, 401 at N=100 (marginal cost 4.00
  queries/transfer) - from TransferSerializer reading
  from_room.apartment.building.*, to_room.apartment.building.*, and
  requested_by.region.* one level beyond what
  TransferViewSet.get_queryset() selected. This endpoint is not called by
  the current frontend (TransfersPage.js uses /api/requests/, not
  /api/transfers/ - see the audit's §6.1), but it remains a reachable
  backend API with a confirmed N+1, fixed in this Group 1 implementation
  phase alongside the (unrelated, more severe) Requests fix.
- This module measures the FIXED code: TransferViewSet.get_queryset() now
  select_related()s the full from_room/to_room -> apartment -> building
  chain and requested_by -> region, matching every field
  TransferSerializer actually reads. Asserts query count stays FLAT.

MEASUREMENT + REGRESSION TEST. No pagination was added - /api/transfers/
remains unpaginated (returns a plain JSON array), per the audit's explicit
instruction not to add pagination without proof it won't break an existing
API contract; see project-quality/performance/PERFORMANCE_FINAL_REPORT.md
for the reasoning.

Run against Django's disposable TEST database (never touches the real
database):

    cd backend
    ENV_FILE=.env.test python manage.py test api.performance_tests.test_transfers_performance -v 2
"""

import re
import time
from collections import Counter
from pathlib import Path

from django.conf import settings
from django.db import connection
from django.test import TestCase
from django.test.utils import CaptureQueriesContext
from rest_framework.test import APIClient

from api.models import (
    User, Region, DormType, Building, Apartment, Room, Student, Transfer,
)

EVIDENCE_DIR = Path(settings.BASE_DIR).parent / 'project-quality' / 'performance' / 'evidence'
EVIDENCE_FILE = EVIDENCE_DIR / 'GROUP1_TRANSFERS_AFTER_QUERY_COUNTS.txt'

_NUMBER_RE = re.compile(r'\d+')


def _shape(sql):
    return _NUMBER_RE.sub('#', sql)


def _summarize(captured_queries):
    shapes = Counter(_shape(q['sql']) for q in captured_queries)
    repeated = {shape: n for shape, n in shapes.items() if n > 1}
    return {'total': len(captured_queries), 'distinct_shapes': len(shapes), 'repeated_shapes': repeated}


def _make_user(email, role, region=None):
    user = User(email=email, username=email, role=role, region=region, first_name='T', last_name='User')
    user.set_password('testpass123')
    user.save()
