"""
Report/export (backend/api/report_exports.py) performance + correctness
regression tests for the Group 1 implementation phase fixes G1-19 and
G1-20.

- G1-20: generate_capacity_report() now calls _load_data(include_students=False)
  since it only ever reads d['all_beds']/d['occupied_bed_ids'] - the
  Student + active-BedAssignment fetch (and its 5 Python-side category
  list comprehensions) _load_data() used to always perform is skipped
  entirely for this one report. dormify_report/student_actions_report/
  manual_review_report all keep the include_students=True default,
  unchanged.
- G1-19: generate_manual_review_report() now computes _student_issues()
  once per student, in a single shared pass
  (_compute_student_issues()), and reuses that result for the 3 sheets
  that need it (summary counts, full exceptions list, unassigned-with-
  issues) instead of each independently re-running the same per-student
  validation logic with its own fresh seen_ids. The 2 structurally
  different builders (duplicate-ID grouping, missing-data-only check)
  are left as their own separate passes.

Both changes are verified to produce byte-for-byte identical workbook
CONTENTS to the original (pre-consolidation) logic - the tests parse the
generated .xlsx directly via openpyxl (already a project dependency, used
by report_exports.py itself) rather than re-deriving expected values from
the same helper functions being tested.

Run against Django's disposable TEST database (never touches the real
database):

    cd backend
    ENV_FILE=.env.test python manage.py test api.performance_tests.test_reports_performance -v 2
"""

